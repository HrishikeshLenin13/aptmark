/** This local workspace follows the user-provided America/Chicago calendar. */
export const WORKSPACE_TIMEZONE = "America/Chicago";
export function calendarDate(at = new Date(), timezone = WORKSPACE_TIMEZONE) {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: timezone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(at);
  const get = (type: string) => parts.find((p) => p.type === type)!.value;
  return `${get("year")}-${get("month")}-${get("day")}`;
}
